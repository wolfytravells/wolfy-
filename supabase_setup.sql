-- WOLFY HOLIDAYS setup: run in Supabase > SQL Editor.
create table if not exists public.traveller_bookings (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 customer_name text not null,
 phone text not null,
 journey_date date not null,
 number_of_days integer not null check(number_of_days between 1 and 90),
 pickup text not null,
 destination text not null,
 passengers integer not null check(passengers between 1 and 60),
 trip_type text not null default 'Other',
 message text default '',
 status text not null default 'Pending' check(status in ('Pending','Confirmed','Cancelled'))
);
alter table public.traveller_bookings enable row level security;
drop policy if exists "Public can submit traveller enquiries" on public.traveller_bookings;
create policy "Public can submit traveller enquiries" on public.traveller_bookings
for insert to anon,authenticated with check(true);
-- Replace owner@example.com with the owner's Supabase Auth email.
drop policy if exists "Owner can read traveller enquiries" on public.traveller_bookings;
create policy "Owner can read traveller enquiries" on public.traveller_bookings
for select to authenticated using((auth.jwt()->>'email')='owner@example.com');
drop policy if exists "Owner can update traveller enquiries" on public.traveller_bookings;
create policy "Owner can update traveller enquiries" on public.traveller_bookings
for update to authenticated using((auth.jwt()->>'email')='owner@example.com')
with check((auth.jwt()->>'email')='owner@example.com');

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('traveller-photos','traveller-photos',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];
drop policy if exists "Owner can upload traveller photos" on storage.objects;
create policy "Owner can upload traveller photos" on storage.objects
for insert to authenticated with check(bucket_id='traveller-photos' and (auth.jwt()->>'email')='owner@example.com');
drop policy if exists "Public can view traveller photos" on storage.objects;
create policy "Public can view traveller photos" on storage.objects
for select to anon,authenticated using(bucket_id='traveller-photos');
